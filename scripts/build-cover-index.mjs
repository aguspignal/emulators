// Regenerates the bundled cover indexes: apps/<app>/assets/covers/<console>.ts
//
//   node scripts/build-cover-index.mjs
//
// Each index maps a ROM's content MD5 to the canonical No-Intro name that the
// libretro thumbnail CDN keys its filenames by. Matching happens entirely
// offline against these tables, and a URL is only ever built from an entry
// found here — never from a user's filename, which would produce confident
// wrong answers (Ruby's box art on Sapphire) and unbounded 404 traffic.
//
// The source DATs come from libretro-database rather than a git submodule:
// the mgba submodule pays for itself as a build dependency, but this is five
// text files from a very large repo. These are finished consoles, so the data
// barely changes — regenerate rarely.
//
// AFTER REGENERATING: add a migration block to packages/storage/src/schema.ts
// resetting `cover_state = 'missing'` rows to 'pending', or existing installs
// keep the old verdict forever. The rule is documented there.

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BASE =
  'https://raw.githubusercontent.com/libretro/libretro-database/master/metadat/no-intro';

/** Which consoles each app bundles. Mirrors the `consoles` in its App.tsx. */
const APPS = {
  gba: ['gb', 'gbc', 'gba'],
  nds: ['nds'],
  threeds: ['3ds'],
};

/** ConsoleId -> the DAT basename, which is also the CDN's system folder. */
const DAT_NAME = {
  gb: 'Nintendo - Game Boy',
  gbc: 'Nintendo - Game Boy Color',
  gba: 'Nintendo - Game Boy Advance',
  nds: 'Nintendo - Nintendo DS',
  '3ds': 'Nintendo - Nintendo 3DS',
};

/**
 * 48 bits. Across ~6,500 entries the birthday probability is ~7.5e-8, but a
 * collision would silently mean a wrong cover, so the caller throws instead.
 */
const KEY_LENGTH = 12;

/**
 * ClrMamePro DAT. Each `game (...)` block carries a game-level `name` before
 * its `rom (...)` line, so the first name match in the block is the canonical
 * one and the md5 is whatever the rom line holds.
 */
function parseDat(text) {
  const entries = new Map();
  let dropped = 0;
  for (const block of text.split(/\bgame\s*\(/).slice(1)) {
    const name = block.match(/^\s*name\s+"([^"]*)"/m)?.[1];
    const md5 = block.match(/\bmd5\s+([0-9A-Fa-f]{32})\b/)?.[1];
    if (!name || !md5) {
      dropped++;
      continue;
    }
    const key = md5.toLowerCase().slice(0, KEY_LENGTH);
    const existing = entries.get(key);
    if (existing !== undefined && existing !== name) {
      throw new Error(
        `MD5 prefix collision on ${key}: "${existing}" vs "${name}". ` +
          `Raise KEY_LENGTH rather than dropping a row.`
      );
    }
    entries.set(key, name);
  }
  return { entries, dropped };
}

/**
 * One `\n`-delimited string, not JSON and not an object literal: Metro turns
 * .json into a literal that Hermes must construct eagerly at require time,
 * where a single string constant lives in the string table and materializes
 * lazily. ~6,500 entries is the difference between a startup hitch and none.
 */
function emit(consoleId, entries) {
  const packed = [...entries.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([key, name]) => `${key} ${name}`)
    .join('\\n');
  return (
    `// GENERATED by scripts/build-cover-index.mjs — do not edit by hand.\n` +
    `// ${DAT_NAME[consoleId]} — ${entries.size} entries.\n` +
    `// Lines are "<md5 prefix, ${KEY_LENGTH} hex> <canonical No-Intro name>".\n` +
    `export const SOURCE =\n  '${packed.replace(/'/g, "\\'")}';\n`
  );
}

const targets = Object.entries(APPS).flatMap(([app, consoles]) =>
  consoles.map((consoleId) => ({ app, consoleId }))
);

for (const { app, consoleId } of targets) {
  const url = `${BASE}/${encodeURIComponent(DAT_NAME[consoleId])}.dat`;
  process.stdout.write(`${consoleId.padEnd(4)} fetching… `);
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url} -> ${response.status} ${response.statusText}`);
  }
  const { entries, dropped } = parseDat(await response.text());
  if (entries.size === 0) {
    throw new Error(`${DAT_NAME[consoleId]} parsed to zero entries — format changed?`);
  }

  const outDir = join(ROOT, 'apps', app, 'assets', 'covers');
  mkdirSync(outDir, { recursive: true });
  const outFile = join(outDir, `${consoleId}.ts`);
  writeFileSync(outFile, emit(consoleId, entries), 'utf8');

  const kb = Math.round(Buffer.byteLength(emit(consoleId, entries)) / 1024);
  process.stdout.write(
    `${entries.size} entries, ~${kb}KB${dropped ? `, ${dropped} unparsed` : ''} -> ` +
      `apps/${app}/assets/covers/${consoleId}.ts\n`
  );
}
